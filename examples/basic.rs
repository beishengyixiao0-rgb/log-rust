//! 基本使用示例 - 演示简单的日志宏

use bitlog::{debug, error, info, warn};

fn main() {
    println!("=== BitLog 基本示例 ===\n");

    // 使用根日志器和便捷的宏
    debug!("这是一条调试消息");
    info!("这是一条信息消息");
    warn!("这是一条警告");
    error!("这是一条错误");
    // fatal!("这是一条致命错误");  // 取消注释以查看致命日志

    // 格式化消息
    info!("用户 {} 登录，id={}", "Alice", 42);
    debug!("正在处理 {} 个项目，来源：{}", 100, "数据库");

    println!("\n=== 基本示例完成 ===");
}
